function getElementPosition(el) {
    const docEl = document.documentElement;
    const docRect = docEl.getBoundingClientRect();
    const elRect = el.getBoundingClientRect();
    return {
        x: elRect.left - docRect.left,
        y: elRect.top - docRect.top,
    };
}

/**
 * 本地补丁：锚点选择器可能带百分号编码（中文 slug 从地址栏进入时就是这样），
 * 原实现直接 querySelector(to.hash) 会抛 SyntaxError，导致带 hash 打开页面时不滚动。
 * 这里先解码再查询，并用 try/catch 兜底。
 */
function findAnchorByHash(hash) {
    if (!hash) return null;
    let decoded = hash;
    try {
        decoded = decodeURIComponent(hash);
    } catch (e) {
        decoded = hash;
    }
    try {
        return document.querySelector(decoded);
    } catch (e) {
        // 选择器非法时退回 id 查找
        try {
            return document.getElementById(decoded.replace(/^#/, ''));
        } catch (e2) {
            return null;
        }
    }
}

const enhanceApp = ({ Vue, router }) => {
    router.options.scrollBehavior = (to, from, savedPosition) => {
        if (savedPosition) {
            return window.scrollTo({
                top: savedPosition.y,
                behavior: 'smooth',
            });
        }
        else if (to.hash) {
            if (Vue.$vuepress.$get('disableScrollBehavior')) {
                return;
            }
            const targetElement = findAnchorByHash(to.hash);
            if (targetElement) {
                return window.scrollTo({
                    top: getElementPosition(targetElement).y,
                    behavior: 'smooth',
                });
            }
        }
        else {
            return window.scrollTo({
                top: 0,
                behavior: 'smooth',
            });
        }
    };
};
export default enhanceApp;
