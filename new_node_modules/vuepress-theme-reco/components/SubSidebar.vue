<script>
import { defineComponent } from 'vue-demi'

/**
 * 本地补丁（第二版）：目录点击改为完全自管滚动。
 *
 * 之前的问题：点击目录走 router-link → vue-router 的 scrollBehavior →
 * vuepress-plugin-smooth-scroll 平滑滚动，中途还可能被
 * @vuepress/plugin-active-header-links 的 scroll-spy 改写 hash，
 * 三方抢时序，于是出现"跳过去又弹回上一个标题"。
 * 现在：
 *   1. 目录项是普通 <a>，点击时 preventDefault，自己算文档绝对坐标后
 *      window.scrollTo({ top, behavior: 'smooth' })，不经过 router；
 *   2. hash 只用 history.replaceState 写回地址栏，不产生滚动副作用；
 *   3. 高亮按滚动位置自算（文档绝对坐标，不用 offsetTop）。
 */
export default defineComponent({
  data () {
    return { activeSlug: '' }
  },

  computed: {
    headers () {
      return this.$showSubSideBar ? this.$page.headers : []
    }
  },

  mounted () {
    this._timers = []
    this._manualScrolled = false
    this._onScroll = this.updateActiveByScroll.bind(this)
    window.addEventListener('scroll', this._onScroll, { passive: true })
    window.addEventListener('resize', this._onScroll)

    // 用户一旦自己滚动（滚轮 / 触摸），就不再在初始化时纠正位置
    this._onUserScroll = () => { this._manualScrolled = true }
    window.addEventListener('wheel', this._onUserScroll, { passive: true })
    window.addEventListener('touchmove', this._onUserScroll, { passive: true })

    // 通过 URL 进入（如带 #锚点 刷新）时，同步一次高亮
    this._onRouteChange = () => {
      const slug = this.hashToSlug(this.$route.hash)
      if (slug) {
        this.activeSlug = slug
      }
      this.$nextTick(this.updateActiveByScroll)
      // 路由（含首次解析）带 hash 时，自己把页面定位到锚点
      if (slug) {
        this._applyInitialHash(true)
      }
    }
    this._removeAfterEach = this.$router.afterEach(this._onRouteChange)

    // 首次进入若带 hash，等页面稳定后按绝对坐标对齐一次
    this._onRouteChange()
    this.updateActiveByScroll()

    // 深链接（直接在地址栏带 #锚点 打开）时，router 的 scrollBehavior 常在
    // 首个路由完成前就执行，此时目标元素还没渲染，导致页面停在第 0 屏。
    // 这里在挂载后自己对齐一次，并在图片等资源加载完成后再校正一次。
    this._applyInitialHash()
    this._onLoad = () => this._applyInitialHash(true)
    if (document.readyState === 'complete') {
      // 已经加载完就只做挂载后那一次
      this._onLoad = null
    } else {
      window.addEventListener('load', this._onLoad)
    }
  },

  beforeDestroy () {
    window.removeEventListener('scroll', this._onScroll)
    window.removeEventListener('resize', this._onScroll)
    window.removeEventListener('wheel', this._onUserScroll)
    window.removeEventListener('touchmove', this._onUserScroll)
    if (this._timers) {
      this._timers.forEach(t => clearTimeout(t))
      this._timers = []
    }
    if (this._onLoad) {
      window.removeEventListener('load', this._onLoad)
      this._onLoad = null
    }
    if (typeof this._removeAfterEach === 'function') {
      this._removeAfterEach()
    }
  },

  methods: {
    hashToSlug (hash) {
      let value = hash || ''
      try {
        value = decodeURIComponent(value)
      } catch (e) {
        value = hash || ''
      }
      return value.replace(/^#/, '')
    },

    getScrollTop () {
      return (
        window.pageYOffset ||
        document.documentElement.scrollTop ||
        document.body.scrollTop ||
        0
      )
    },

    getAnchorTop (slug) {
      const el = document.getElementById(slug)
      if (!el) return null
      // 文档绝对坐标：getBoundingClientRect 相对视口，加滚动量才是全文档位置
      return Math.max(0, Math.round(el.getBoundingClientRect().top + this.getScrollTop()))
    },

    // 用"文档绝对坐标"判断当前所在小节；offsetTop 是相对 offsetParent 的坐标，不能用
    updateActiveByScroll () {
      const headers = this.headers || []
      if (!headers.length) {
        this.activeSlug = ''
        return
      }
      const scrollTop = this.getScrollTop()
      const buffer = 90
      let current = headers[0].slug
      for (let i = 0; i < headers.length; i++) {
        const slug = headers[i].slug
        const el = document.getElementById(slug)
        if (!el) continue
        const top = el.getBoundingClientRect().top + scrollTop
        if (scrollTop + buffer >= top) {
          current = slug
        } else {
          break
        }
      }
      if (current !== this.activeSlug) {
        this.activeSlug = current
      }
    },

    // 点击目录：自己滚，不经过 router / scrollBehavior，杜绝回弹
    onAnchorClick (event, slug) {
      // 保留 Ctrl / Shift / Cmd 点击"在新窗口打开"的原生行为
      if (event && (event.ctrlKey || event.metaKey || event.shiftKey || event.altKey)) {
        return
      }
      if (event) {
        event.preventDefault()
        event.stopPropagation()
      }

      const top = this.getAnchorTop(slug)
      if (top === null) return

      this.activeSlug = slug

      try {
        window.scrollTo({ top, behavior: 'smooth' })
      } catch (e) {
        window.scrollTo(0, top)
      }

      // 只改地址栏，不用 location.hash 赋值（那会触发浏览器原生跳转导致二次滚动）
      try {
        const url = window.location.pathname + window.location.search + '#' + slug
        window.history.replaceState(window.history.state, '', url)
      } catch (e) {}
    },

    // 带 hash 进入时，自己把页面滚到目标标题（不依赖 router 首次 scrollBehavior）
    _applyInitialHash (force) {
      const slug = this.hashToSlug(this.$route.hash || window.location.hash)
      if (!slug) return
      const apply = () => {
        if (this._manualScrolled) return
        const top = this.getAnchorTop(slug)
        if (top === null) return
        const cur = Math.round(this.getScrollTop())
        // force=true 时只修正明显偏差，避免打断用户手动滚动
        if (!force || Math.abs(cur - top) > 24) {
          window.scrollTo(0, top)
          this.activeSlug = slug
        }
      }
      // 首屏布局可能在挂载后才稳定（字体、图片、目录宽度），重试几次
      this.$nextTick(() => {
        apply()
        ;[280, 900, 1800].forEach(ms => {
          const t = setTimeout(apply, ms)
          this._timers.push(t)
        })
      })
    },

    isLinkActive (header) {
      return header.slug === this.activeSlug
    }
  },

  render (h) {
    return h('ul', {
      class: { 'sub-sidebar-wrapper': true },
      style: { width: this.headers.length > 0 ? '12rem' : '0' }
    }, [
      ...this.headers.map(header => {
        return h('li', {
          class: {
            active: this.isLinkActive(header),
            [`level-${header.level}`]: true
          },
          attrs: { key: header.title }
        }, [
          h('a', {
            class: { 'sidebar-link': true, [`reco-side-${header.slug}`]: true },
            attrs: { href: `${this.$page.path}#${header.slug}` },
            on: {
              click: (event) => this.onAnchorClick(event, header.slug)
            }
          }, header.title)
        ])
      })
    ])
  }
})
</script>

