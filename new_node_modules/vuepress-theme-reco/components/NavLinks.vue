<template>
  <nav class="nav-links" v-if="userLinks.length || repoLink">
    <!-- user links -->
    <div class="nav-item" v-for="item in userLinks" :key="item.link">
      <DropdownLink v-if="item.type === 'links'" :item="item" />
      <NavLink v-else :item="item" />
    </div>

    <!-- repo link -->
    <a v-if="repoLink" :href="repoLink" class="repo-link" target="_blank" rel="noopener noreferrer">
      <reco-icon :icon="`reco-${repoLabel.toLowerCase()}`" />
      {{ repoLabel }}
      <OutboundLink />
    </a>
  </nav>
</template>

<script>
import { defineComponent, computed } from 'vue-demi'
import { RecoIcon } from '@vuepress-reco/core/lib/components'
import DropdownLink from '@theme/components/DropdownLink'
import { resolveNavLinkItem } from '@theme/helpers/utils'
import NavLink from '@theme/components/NavLink'

export default defineComponent({
  components: { NavLink, DropdownLink, RecoIcon },

  computed: {
    userNav () {
      return this.$themeLocaleConfig.nav || this.$themeConfig.nav || []
    },

    nav () {
      const locales = this.$site.locales || {}

      if (locales && Object.keys(locales).length > 1) {
        const currentLink = this.$page.path
        const routes = this.$router.options.routes
        const themeLocales = this.$themeConfig.locales || {}
        const languageDropdown = {
          text: this.$themeLocaleConfig.selectText || 'Languages',
          items: Object.keys(locales).map(path => {
            const locale = locales[path]
            const text = themeLocales[path] && themeLocales[path].label || locale.lang
            let link
            if (locale.lang === this.$lang) {
              link = currentLink
            } else {
              link = currentLink.replace(this.$localeConfig.path, path)
              if (!routes.some(route => route.path === link)) {
                link = path
              }
            }
            return { text, link }
          })
        }

        return [...this.userNav, languageDropdown]
      }

      const blogConfig = this.$themeConfig.blogConfig || {}
      const isHasCategory = this.userNav.some(item => {
        if (blogConfig.category) {
          return item.text === (blogConfig.category.text || '分类')
        } else {
          return true
        }
      })
      const isHasTag = this.userNav.some(item => {
        if (blogConfig.tag) {
          return item.text === (blogConfig.tag.text || '标签')
        } else {
          return true
        }
      })

      if (!isHasCategory && Object.hasOwnProperty.call(blogConfig, 'category')) {
        const category = blogConfig.category
        const $categories = this.$categories
        this.userNav.splice(parseInt(category.location || 2) - 1, 0, {
          items: $categories.list.map(item => {
            item.link = item.path
            item.text = item.name
            return item
          }),
          text: category.text || this.$recoLocales.category,
          type: 'links',
          icon: 'reco-category'
        })
      }

      if (!isHasTag && Object.hasOwnProperty.call(blogConfig, 'tag')) {
        const tag = blogConfig.tag
        this.userNav.splice(parseInt(tag.location || 3) - 1, 0, {
          link: '/tag/',
          text: tag.text || this.$recoLocales.tag,
          type: 'links',
          icon: 'reco-tag'
        })
      }

      return this.userNav
    },

    userLinks () {
      return (this.nav || []).map(link => {
        return Object.assign(resolveNavLinkItem(link), {
          items: (link.items || []).map(resolveNavLinkItem)
        })
      })
    },

    repoLink () {
      const { repo } = this.$themeConfig

      if (repo) {
        return /^https?:/.test(repo)
          ? repo
          : `https://github.com/${repo}`
      }

      return ''
    },

    repoLabel () {
      if (!this.repoLink) return ''
      if (this.$themeConfig.repoLabel) {
        return this.$themeConfig.repoLabel
      }

      const repoHost = this.repoLink.match(/^https?:\/\/[^/]+/)[0]
      const platforms = ['GitHub', 'GitLab', 'Bitbucket']
      for (let i = 0; i < platforms.length; i++) {
        const platform = platforms[i]
        if (new RegExp(platform, 'i').test(repoHost)) {
          return platform
        }
      }

      return 'Source'
    }
  }
})
</script>

